/** Letters for a method the owner added without a logo. */
export function initials(name: string): string {
  const words = name.trim().split(/\s+/).filter(Boolean);
  return (words.length > 1 ? words[0][0] + words[1][0] : (words[0] ?? '?').slice(0, 2)).toUpperCase();
}

const PALETTE = ['#0d6d64', '#7B2CBF', '#1B4F9C', '#E30613', '#F7941D', '#00A859', '#0E3B6E'];

/** A stable colour for a name, so the same method always looks the same. */
export function colourOf(name: string): string {
  let h = 0;
  for (const ch of name) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return PALETTE[h % PALETTE.length];
}
